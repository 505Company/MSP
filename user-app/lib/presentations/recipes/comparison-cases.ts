export function comparisonRecipeCases(itemCount: number): RecipeMaterial[] {
  if (!Number.isInteger(itemCount) || itemCount < 2 || itemCount > items.length) throw Error('Unsupported comparison cardinality')
  return ['short', 'medium', 'long'].map((id, volume) => ({ id, synthetic: true, itemCount,
    fragments: [{ id: 'f-title', text: 'Как изменился опыт покупателей' }, { id: 'f-context', text: 'Доля успешных действий; синтетические данные за два периода' },
      ...items.slice(0, itemCount).flatMap((item, index) => [
        { id: `f-${index + 1}-heading`, text: item[0] }, { id: `f-${index + 1}-body`, text: item[volume + 1] },
        { id: `f-${index + 1}-current`, text: `${[72, 61, 48, 83, 59, 44, 68, 91][index]}% в 2027` },
        { id: `f-${index + 1}-previous`, text: `${[54, 65, 32, 77, 59, 28, 70, 86][index]}% в 2026` },
      ]),
    ],
  }))
}
